    public const uint ASFW_ANY = 0xFFFFFFFF;

    /// <summary>Work area (in physical pixels) of the monitor under a point, or the primary monitor.</summary>
    public static RECT WorkAreaAt(POINT point)
    {
        var monitor = MonitorFromPoint(point, MONITOR_DEFAULTTONEAREST);
        return WorkArea(monitor);
    }

    public static RECT WorkArea(IntPtr monitor)
    {
        var info = new MONITORINFO { cbSize = Marshal.SizeOf<MONITORINFO>() };
        if (monitor != IntPtr.Zero && GetMonitorInfoW(monitor, ref info))
        {
            return info.rcWork;
        }
        var fallback = System.Windows.SystemParameters.WorkArea;
        return new RECT { Left = (int)fallback.Left, Top = (int)fallback.Top, Right = (int)fallback.Right, Bottom = (int)fallback.Bottom };
    }

    public static bool IsKeyDown(int virtualKey) => (GetAsyncKeyState(virtualKey) & 0x8000) != 0;
